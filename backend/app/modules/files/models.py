from __future__ import annotations

import enum
import uuid
from datetime import datetime

from sqlalchemy import BigInteger, DateTime, ForeignKey, Integer, String, func
from sqlalchemy.dialects.postgresql import UUID as PG_UUID
from sqlalchemy.orm import Mapped, mapped_column

from app.infrastructure.database.enum_column import str_enum
from app.infrastructure.database.mixins import UUIDPrimaryKeyMixin
from app.infrastructure.database.session import Base


class FileVisibility(enum.StrEnum):
    PUBLIC = "public"
    PRIVATE = "private"


class FilePurpose(enum.StrEnum):
    """What an upload is for. Each purpose has its own rules in files/policies.py."""

    AVATAR = "avatar"
    ORGANIZATION_LOGO = "organization_logo"
    EVENT_POSTER = "event_poster"


class File(UUIDPrimaryKeyMixin, Base):
    """
    Metadata only: the bytes live in object storage (files/policies.py decides what is
    kept and how). `storage_key` is generated by the server and never shown to clients;
    `mime_type` is what the server encoded, not what the client claimed. Nothing the client
    sent (file name, content type) is stored.
    """

    __tablename__ = "files"

    owner_user_id: Mapped[uuid.UUID | None] = mapped_column(
        PG_UUID(as_uuid=True),
        ForeignKey("users.id", ondelete="SET NULL"),
        nullable=True,
        index=True,
    )
    purpose: Mapped[FilePurpose] = mapped_column(
        str_enum(FilePurpose, name="file_purpose"), nullable=False
    )
    # The organization an upload was made for (a logo, or the organizer of a poster).
    organization_id: Mapped[uuid.UUID | None] = mapped_column(
        PG_UUID(as_uuid=True),
        ForeignKey("organizations.id", ondelete="SET NULL", name="fk_files_organization_id"),
        nullable=True,
    )
    storage_key: Mapped[str] = mapped_column(String(512), nullable=False)
    mime_type: Mapped[str] = mapped_column(String(255), nullable=False)
    size_bytes: Mapped[int] = mapped_column(BigInteger, nullable=False)
    width: Mapped[int] = mapped_column(Integer, nullable=False)
    height: Mapped[int] = mapped_column(Integer, nullable=False)
    visibility: Mapped[FileVisibility] = mapped_column(
        str_enum(FileVisibility, name="file_visibility"),
        nullable=False,
        default=FileVisibility.PRIVATE,
    )
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now(), nullable=False
    )
