from typing import Protocol


class StorageError(Exception):
    """The storage backend failed, or was asked for something it must never do."""


class Storage(Protocol):
    """
    Where file bytes live. The database keeps only metadata and the key.

    Keys are generated by the server, never taken from a client. Backends still refuse any
    key that could point outside their own area (see validate_key), as a second line of defence.

    Two backends implement this: local disk (development and tests) and any S3-compatible
    object store (Cloudflare R2 in production, MinIO locally). Nothing above this interface
    knows which one is in use.
    """

    async def put(self, key: str, data: bytes, *, content_type: str) -> None: ...

    async def get(self, key: str) -> bytes: ...

    async def delete(self, key: str) -> None:
        """Deleting a key that does not exist is not an error."""
        ...

    async def exists(self, key: str) -> bool: ...


def validate_key(key: str) -> None:
    """
    The rules every backend applies to every key, before touching storage: relative, forward
    slashes only, no empty or dot segments, no NUL.
    """
    if not key or key.startswith(("/", "\\")) or "\\" in key or "\x00" in key:
        raise StorageError("Invalid storage key.")
    if any(part in ("", ".", "..") for part in key.split("/")):
        raise StorageError("Invalid storage key.")
